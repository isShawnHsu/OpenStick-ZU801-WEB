function t(key, vars) {
  var dict = I18N[state.lang] || I18N.zh;
  var s = dict[key];
  if (!s) s = I18N.zh[key];
  if (!s) s = key;
  if (vars) {
    Object.keys(vars).forEach(function (k) {
      s = s.split('{' + k + '}').join(String(vars[k]));
    });
  }
  return s;
}

function esc(v) {
  if (v === null || v === undefined) return '';
  return String(v).replace(/[&<>"']/g, function (c) {
    return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
  });
}

function attr(v) { return esc(v); }

function bytes(n) {
  n = Number(n || 0);
  if (n < 1024) return n + ' B';
  var u = ['KB', 'MB', 'GB', 'TB'];
  var i = -1;
  do { n /= 1024; i++; } while (n >= 1024 && i < u.length - 1);
  return n.toFixed(n >= 100 ? 0 : n >= 10 ? 1 : 2) + ' ' + u[i];
}

function rate(n) {
  n = Number(n || 0);
  if (n < 1024) return n.toFixed(0) + ' B/s';
  return bytes(n) + '/s';
}

function pct(n) {
  if (window.isFinite(n)) return Math.max(0, Math.min(100, n)).toFixed(0) + '%';
  return '0%';
}

function dateText(ts) {
  if (!ts) return '-';
  var d = new Date(Number(ts) * 1000);
  if (isNaN(d.getTime())) return '-';
  return d.toLocaleString();
}

function shortMask(v, keep) {
  if (!v) return '-';
  v = String(v);
  if (v.length <= (keep || 6) * 2) return v;
  return v.slice(0, keep || 6) + '…' + v.slice(-4);
}

function yesNo(v) { return v ? t('common.yes') : t('common.no'); }

function pill(text, kind) {
  return '<span class="pill ' + (kind || '') + '">' + esc(text) + '</span>';
}

function signalKind(q) {
  q = Number(q || 0);
  if (q >= 60) return 'ok';
  if (q >= 30) return 'warn';
  return 'bad';
}

function bar(percent, kind) {
  var p = Math.max(0, Math.min(100, Number(percent || 0)));
  return '<div class="bar ' + (kind || '') + '"><span style="width:' + p.toFixed(1) + '%"></span></div>';
}
